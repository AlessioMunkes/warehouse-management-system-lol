import PDFDocument from 'pdfkit';

const dash = '-';

const generateSection18APdf = async ({
  certificateNumber,
  issueDate,
  settings = {},
  donor = {},
  donation = {},
}) => {
  const doc = new PDFDocument({ size: 'A4', margin: 56 });
  const chunks = [];

  const done = new Promise((resolve, reject) => {
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', resolve);
    doc.on('error', reject);
  });

  const form = donor.section18aForm || {};
  const orgName = settings.organisation_name || 'Organisation';
  const footerText = settings.footer_text
    || 'This certificate was electronically generated by the Ladles of Love Warehouse Management System and does not require a handwritten signature.';

  doc.fontSize(18).font('Helvetica-Bold').text('Section 18A Tax Certificate', { align: 'center' });
  doc.moveDown(0.4);
  doc.fontSize(13).font('Helvetica-Bold').text(orgName, { align: 'center' });
  if (settings.pbo_number) doc.fontSize(10).text(`PBO Number: ${settings.pbo_number}`, { align: 'center' });
  if (settings.npo_number) doc.fontSize(10).text(`NPO Number: ${settings.npo_number}`, { align: 'center' });
  if (settings.section18a_reference) doc.fontSize(10).text(`Section 18A Reference: ${settings.section18a_reference}`, { align: 'center' });
  if (settings.physical_address) doc.fontSize(9).text(`Physical Address: ${settings.physical_address}`, { align: 'center' });
  if (settings.postal_address) doc.fontSize(9).text(`Postal Address: ${settings.postal_address}`, { align: 'center' });
  doc.fontSize(9).text(
    [settings.contact_phone, settings.contact_email, settings.website].filter(Boolean).join(' | '),
    { align: 'center' }
  );
  doc.moveDown(1);

  doc.fontSize(11).font('Helvetica-Bold').text('Certificate Details');
  doc.font('Helvetica').fontSize(10);
  doc.text(`Certificate number: ${certificateNumber}`);
  doc.text(`Issue date: ${issueDate}`);
  doc.moveDown(0.75);

  doc.fontSize(11).font('Helvetica-Bold').text('Donor Details');
  doc.font('Helvetica').fontSize(10);
  doc.text(`Donor type: ${form.donorType || dash}`);
  doc.text(`Full name / Company name: ${form.fullNameOrCompanyName || donor.name || dash}`);
  doc.text(`ID / Registration number: ${form.idNumber || form.registrationNumber || dash}`);
  doc.text(`Income tax number: ${form.incomeTaxNumber || donor.taxReference || dash}`);
  doc.text(`Email: ${form.email || donor.contact || dash}`);
  doc.text(`Phone: ${form.phone || dash}`);
  doc.text(`Physical address: ${form.physicalAddress || dash}`);
  doc.text(`Postal address: ${form.postalAddress || dash}`);
  doc.moveDown(0.75);

  doc.fontSize(11).font('Helvetica-Bold').text('Donation Details');
  doc.font('Helvetica').fontSize(10);
  doc.text(`Donation ID: ${donation.id ?? dash}`);
  doc.text(`Category: ${donation.donation_category || dash}`);
  doc.text(`Estimated value (ZAR): ${donation.estimated_value_zar ?? dash}`);
  doc.text(`Received: ${donation.received_at || dash}`);
  if (Array.isArray(donation.items) && donation.items.length) {
    doc.moveDown(0.4);
    doc.font('Helvetica-Bold').text('Items:');
    doc.font('Helvetica');
    donation.items.forEach((item, idx) => {
      doc.text(`${idx + 1}. ${item.description || 'Item'} - ${item.quantity ?? ''} ${item.unit || ''}`.trim());
    });
  }
  doc.moveDown(0.75);

  doc.fontSize(11).font('Helvetica-Bold').text('Declaration');
  doc.font('Helvetica').fontSize(10).text(
    form.declarationAccepted
      ? `The donor declaration was accepted electronically on ${form.declaredAt || issueDate}.`
      : 'The donor declaration was captured electronically.'
  );
  doc.moveDown(0.75);

  doc.fontSize(11).font('Helvetica-Bold').text('Authorised Signatory');
  doc.font('Helvetica').fontSize(10);
  doc.text(`Name: ${settings.signature_name || dash}`);
  doc.text(`Position: ${settings.signature_title || dash}`);
  doc.moveDown(1);

  doc.fontSize(8).font('Helvetica-Oblique').text(footerText);

  doc.end();
  await done;

  return {
    buffer: Buffer.concat(chunks),
    filename: `section-18a-${certificateNumber}.pdf`,
    contentType: 'application/pdf',
  };
};

export default { generateSection18APdf };
