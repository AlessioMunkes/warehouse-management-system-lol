// ─────────────────────────────────────────────────────────────
// server/src/services/donationEmail.service.js
//
// Donation emails and the Section 18A certificate: sending and logging
// each email, the donor's secure Section 18A form, issuing and
// downloading certificates, Email history and resending, and the
// certificate settings. The wording is in donationEmailContent.js;
// recording a donation is in donation.service.js, which calls
// sendThankYouEmail once a donation is saved.
//
// Every email runs AFTER the donation is durably recorded and never
// rolls it back. A failure to send or log is surfaced in emailResults
// for the caller, the same "record first, notify second" shape as the
// rest of the donation code. Anonymous donors and donors without a
// valid email are simply skipped, not errored.
// ─────────────────────────────────────────────────────────────
import crypto from 'crypto';
import pool from '../config/db.js';
import donationModel from '../repositories/donation.repository.js';
import { createNotification } from '../repositories/notification.repository.js';
import gmailRepository from '../repositories/gmail.repository.js';
import certificateSettingsService from './certificateSettings.service.js';
import communications from './communications.service.js';
import pdfProvider from '../integrations/pdf.provider.js';
import { appBaseUrl, missingAddressMessage } from '../config/appUrl.js';
import {
  EMAIL_RE,
  donorEmailFor,
  generateThankYouEmailContent,
  generateSection18ACertificateEmailContent,
  generateSection18AHandoffEmailContent,
} from './donationEmailContent.js';

const fail = (status, message) => {
  const err = new Error(message);
  err.status = status;
  throw err;
};

const hashSection18AToken = (token) =>
  crypto.createHash('sha256').update(String(token)).digest('hex');

// Null when this server has no web address to build the link from: no
// token is saved for a link nobody can open.
const createSection18AFormToken = async (donationId) => {
  const base = appBaseUrl('section18a');
  if (!base) return null;
  const token = crypto.randomBytes(32).toString('base64url');
  const expiresAt = new Date(Date.now() + 1000 * 60 * 60 * 24 * 30);
  await donationModel.saveSection18AFormToken({
    donationId,
    tokenHash: hashSection18AToken(token),
    expiresAt,
  });
  return {
    token,
    url: `${base}/section-18a/${encodeURIComponent(token)}`,
    expiresAt,
  };
};

const normaliseCertificateSettings = (settings = {}) => ({
  organisation_name: settings.organisation_name ?? settings.organisationName ?? '',
  logo_url: settings.logo_url ?? settings.logoUrl ?? '',
  pbo_number: settings.pbo_number ?? settings.pboNumber ?? '',
  npo_number: settings.npo_number ?? settings.npoNumber ?? '',
  section18a_reference: settings.section18a_reference ?? settings.section18AReference ?? '',
  physical_address: settings.physical_address ?? settings.physicalAddress ?? settings.organisation_address ?? '',
  postal_address: settings.postal_address ?? settings.postalAddress ?? '',
  contact_phone: settings.contact_phone ?? settings.contactPhone ?? '',
  contact_email: settings.contact_email ?? settings.contactEmail ?? '',
  website: settings.website ?? '',
  signature_name: settings.signature_name ?? settings.signatureName ?? settings.contact_name ?? '',
  signature_title: settings.signature_title ?? settings.signatureTitle ?? '',
  certificate_prefix: settings.certificate_prefix ?? settings.certificatePrefix ?? '18A',
  footer_text: settings.footer_text ?? settings.footerText ?? 'This certificate was electronically generated by the Ladles of Love Warehouse Management System and does not require a handwritten signature.',
});

// Logs one send attempt. This is the SINGLE Gmail send + persist point
// for Donation emails: email.provider.sendEmail (→ gmail.service.sendEmail)
// is called only here, and every outcome — SENT and FAILED — is written
// via donationModel.logDonationEmail. Callers must not add their own
// logDonationEmail fallback or one send produces two history rows.
const logEmailAttempt = async ({ donation, donationId, donorId = null, certificateId = null, emailType, recipient, recipientName = null, subject, email, sentByUserId = null }) => {
  const resolvedDonationId = donation?.id ?? donationId;
  const resolvedRecipientName = recipientName || donation?.donor_name || null;
  const resolvedDonorId = donorId ?? donation?.donor_id ?? null;
  try {
    const result = await communications.send({
      type: emailType === 'THANK_YOU' ? 'donation_thank_you'
        : certificateId ? 'section_18a'
        : 'section_18a_handoff',
      to: recipient,
      subject,
      text: email.text,
      html: email.html,
      attachments: email.attachments,
      related: { type: 'donation', id: resolvedDonationId },
      sentBy: sentByUserId,
      sendAs: null,
    });
    const success = Boolean(result && result.sent === true);
    return await donationModel.logDonationEmail({
      donationId: resolvedDonationId,
      donorId: resolvedDonorId,
      certificateId,
      emailType,
      recipient,
      recipientEmail: recipient,
      recipientName: resolvedRecipientName,
      subject,
      status: success ? 'SENT' : 'FAILED',
      providerMessageId: success ? (result.messageId || null) : null,
      gmailMessageId: success ? (result.messageId || null) : null,
      gmailThreadId: success ? (result.threadId || null) : null,
      errorMessage: success ? null : (result.reason || result.error || 'Provider reported a failure.'),
      sentByUserId,
    });
  } catch (err) {
    return await donationModel.logDonationEmail({
      donationId: resolvedDonationId,
      donorId: resolvedDonorId,
      certificateId,
      emailType,
      recipient,
      recipientEmail: recipient,
      recipientName: resolvedRecipientName,
      subject,
      status: 'FAILED',
      errorMessage: err.message,
      sentByUserId,
    });
  }
};

const sendThankYouEmail = async (donation, sentByUserId = null) => {
  const recipient = donorEmailFor(donation);
  if (!recipient) return null;
  let section18ALink = null;
  if (donation.section_18a_status === 'queued' || donation.section_18a_status === 'qualifying_pending_donor') {
    const token = await createSection18AFormToken(donation.id);
    if (!token) {
      // The donor is owed that link. Do not send a thank-you that leaves it
      // out; record the failure so it shows in Email history to be resent.
      return await donationModel.logDonationEmail({
        donationId: donation.id,
        donorId: donation.donor_id ?? null,
        certificateId: null,
        emailType: 'THANK_YOU',
        recipient,
        recipientEmail: recipient,
        recipientName: donation.donor_name || null,
        subject: 'Thank you for your donation',
        status: 'FAILED',
        providerMessageId: null,
        gmailMessageId: null,
        gmailThreadId: null,
        errorMessage: missingAddressMessage('section18a'),
        sentByUserId,
      });
    }
    section18ALink = token.url;
  }
  const emailContent = generateThankYouEmailContent(donation, section18ALink);
  return await logEmailAttempt({
    donation,
    donationId: donation.id,
    emailType: 'THANK_YOU',
    recipient,
    subject: 'Thank you for your donation',
    email: {
      text: emailContent.text,
      html: emailContent.html,
    },
    sentByUserId,
  });
};

const notifySection18AEmailFailed = async (donation) => {
  await createNotification(pool, {
    type: 'section18a_email_failed',
    title: 'Section 18A email failed',
    body: `Certificate email for donation #${donation.id} failed.`,
    entityType: 'donation',
    entityId: donation.id,
    targetRoles: ['manager', 'admin'],
    avoidDuplicate: true,
  });
};

// Returns the existing certificate for the donation, or creates a new
// one if none exists yet. Never regenerates one that is already there.
const getOrCreateSection18ACertificate = async (donation, actorId) => {
  const existing = await donationModel.getSection18ACertificateByDonationId(donation.id);
  if (existing) return existing;
  // Load organisation settings from the dedicated certificate settings service.
  // This ensures we use the persistent, database-backed settings from
  // certificate_settings table instead of hardcoded values.
  const certificateSettings = normaliseCertificateSettings(await certificateSettingsService.getSettings());

  const donorSnapshot = {
    name:         donation.donor_name,
    contact:      donation.donor_contact,
    taxReference: donation.donor_tax_reference,
    section18aForm: donation.section_18a_form || null,
  };
  const donationSnapshot = {
    id:                  donation.id,
    donation_category:   donation.donation_category,
    estimated_value_zar: donation.estimated_value_zar,
    received_at:         donation.received_at,
    items:               donation.items || [],
  };

  const { certificate } = await donationModel.createSection18ACertificate({
    donationId:   donation.id,
    issuedBy:     actorId,
    settings:     certificateSettings,
    donorSnapshot,
    donationSnapshot,
    buildPdf: async ({ certificateNumber, issueDate }) =>
      pdfProvider.generateSection18APdf({
        certificateNumber,
        issueDate,
        settings: certificateSettings,
        donor:     donorSnapshot,
        donation:  donationSnapshot,
      }),
  });

  return certificate;
};

const validateSection18AForm = (payload = {}) => {
  const required = [
    'donorType',
    'fullNameOrCompanyName',
    'incomeTaxNumber',
    'email',
    'phone',
    'physicalAddress',
    'postalAddress',
  ];
  const errors = {};
  required.forEach((field) => {
    if (!String(payload[field] ?? '').trim()) errors[field] = 'This field is required.';
  });
  if (!String(payload.idNumber ?? payload.registrationNumber ?? '').trim()) {
    errors.idOrRegistration = 'ID number or registration number is required.';
  }
  if (payload.declarationAccepted !== true) {
    errors.declarationAccepted = 'Declaration must be accepted.';
  }
  if (payload.email && !EMAIL_RE.test(String(payload.email).trim())) {
    errors.email = 'Enter a valid email address.';
  }
  if (Object.keys(errors).length) {
    const err = new Error('Section 18A form validation failed.');
    err.status = 400;
    err.details = errors;
    throw err;
  }
  return {
    donorType: String(payload.donorType).trim(),
    fullNameOrCompanyName: String(payload.fullNameOrCompanyName).trim(),
    idNumber: String(payload.idNumber ?? '').trim() || null,
    registrationNumber: String(payload.registrationNumber ?? '').trim() || null,
    incomeTaxNumber: String(payload.incomeTaxNumber).trim(),
    email: String(payload.email).trim().toLowerCase(),
    phone: String(payload.phone).trim(),
    physicalAddress: String(payload.physicalAddress).trim(),
    postalAddress: String(payload.postalAddress).trim(),
    declarationAccepted: true,
    declaredAt: new Date().toISOString(),
  };
};

const getSection18AFormByToken = async (token) => {
  if (!token) fail(400, 'Section 18A token is required.');
  const donation = await donationModel.getDonationBySection18AFormTokenHash(hashSection18AToken(token));
  if (!donation) fail(404, 'Section 18A form link was not found.');
  if (donation.section_18a_form_token_expires_at && new Date(donation.section_18a_form_token_expires_at) < new Date()) {
    fail(410, 'Section 18A form link has expired.');
  }
  if (donation.section_18a_status === 'issued' || donation.section_18a_form_submitted_at) {
    return { donationId: donation.id, status: donation.section_18a_status || 'submitted', completed: true };
  }
  return {
    donationId: donation.id,
    status: donation.section_18a_status,
    donorName: donation.donor_name,
    donorEmail: donorEmailFor(donation),
    estimatedValueZar: donation.estimated_value_zar,
    completed: false,
  };
};

const submitSection18AForm = async (token, payload = {}) => {
  const formData = validateSection18AForm(payload);
  const current = await getSection18AFormByToken(token);
  if (current.completed) fail(409, 'Section 18A form has already been submitted.');

  const donation = await donationModel.saveSection18AFormSubmission({
    donationId: current.donationId,
    formData,
  });
  if (!donation) fail(404, 'Donation not found.');

  const handoffDonation = {
    ...donation,
    donor_name: formData.fullNameOrCompanyName,
    donor_contact: formData.email,
    donor_tax_reference: formData.incomeTaxNumber,
    section_18a_form: formData,
  };
  const connectedGmail = await gmailRepository.findLatestConnection();
  const recipient = connectedGmail?.gmail_email;
  if (!recipient) {
    await donationModel.logDonationEmail({
      donation: handoffDonation,
      donationId: donation.id,
      emailType: 'SECTION_18A',
      recipient: 'connected Gmail account',
      recipientEmail: null,
      recipientName: 'Finance/Tax',
      subject: 'Finance/Tax handoff: Section 18A donor details',
      status: 'FAILED',
      errorMessage: 'No connected Gmail account is available for the Section 18A handoff.',
      sentByUserId: null,
    });
    fail(503, 'No connected Gmail account is available for the Section 18A handoff.');
  }

  const emailContent = generateSection18AHandoffEmailContent(handoffDonation, formData);
  const sent = await logEmailAttempt({
    donation: handoffDonation,
    donationId: donation.id,
    emailType: 'SECTION_18A',
    recipient,
    recipientName: 'Finance/Tax',
    subject: emailContent.subject,
    email: {
      text: emailContent.text,
      html: emailContent.html,
    },
    sentByUserId: null,
  });

  return {
    donationId: donation.id,
    status: 'submitted',
    handoffEmail: sent,
  };
};

const sendSection18ACertificateEmail = async (donation, actorId) => {
  if (donation.section_18a_status !== 'queued' && donation.section_18a_status !== 'issued') {
    return null;
  }
  const recipient = donorEmailFor(donation);
  if (!recipient) return null;

  // Certificate creation touches the PDF lib, settings and a DB write, and
  // can throw (misconfigured settings, PDF failure). That must surface as a
  // failed email-log row — recoverable via the email-history resend path —
  // and never as an uncaught exception that 500s the recorded donation.
  // This logDonationEmail is the only direct write outside logEmailAttempt:
  // it covers the pre-send failure where there is no Gmail attempt to log.
  let certificate;
  let emailContent;
  try {
    certificate = await getOrCreateSection18ACertificate(donation, actorId);
    const emailSettings = normaliseCertificateSettings(await certificateSettingsService.getSettings());
    emailContent = generateSection18ACertificateEmailContent(donation, certificate, emailSettings);
  } catch (err) {
    console.error('[sendSection18ACertificateEmail:prepare]', err);
    const failedLog = await donationModel.logDonationEmail({
      donation,
      donationId: donation.id,
      certificateId: certificate?.id ?? null,
      emailType: 'SECTION_18A',
      recipient,
      recipientEmail: recipient,
      recipientName: donation.donor_name || null,
      subject: 'Your Section 18A tax certificate',
      status: 'FAILED',
      errorMessage: err.message,
      sentByUserId: actorId ?? null,
    });
    await notifySection18AEmailFailed(donation);
    return failedLog;
  }

  const sent = await logEmailAttempt({
    donation,
    donationId:    donation.id,
    certificateId: certificate.id,
    emailType: 'SECTION_18A',
    recipient,
    subject: 'Your Section 18A tax certificate',
    email: emailContent,
    sentByUserId: actorId ?? null,
  });
  if (sent?.status === 'FAILED') {
    await notifySection18AEmailFailed(donation);
  }
  return sent;
};

const generateSection18ACertificate = async (donationId, userId) => {
  const donation = await donationModel.getDonationById(donationId);
  if (!donation) fail(404, 'Donation not found.');

  if (await donationModel.getSection18ACertificateByDonationId(donationId)) {
    fail(409, 'A Section 18A certificate already exists for this donation.');
  }
  if (!donation.donor_consent_given || !String(donation.donor_tax_reference || '').trim()) {
    fail(400, 'Donor consent and tax reference are required to issue a certificate.');
  }
  if (donation.section_18a_status !== 'queued' && donation.section_18a_status !== 'issued') {
    fail(400, 'This donation is not ready for a Section 18A certificate.');
  }

  return await getOrCreateSection18ACertificate(donation, userId);
};

const downloadSection18ACertificate = async (donationId) => {
  const certificate = await donationModel.getSection18ACertificateByDonationId(donationId);
  if (!certificate) fail(404, 'No Section 18A certificate exists for this donation.');
  return {
    buffer:            certificate.pdf_content,
    filename:          certificate.pdf_filename,
    contentType:       certificate.pdf_content_type,
    certificateNumber: certificate.certificate_number,
  };
};

const listEmailHistory = async ({ search = null, emailType = null, status = null, limit = 200, offset = 0 } = {}) =>
  // History is served from the database only — Gmail is never queried.
  await donationModel.listEmailHistory({ search, emailType, status, limit, offset });

const normaliseEmailType = (value) => {
  const v = String(value || '');
  if (v === 'thank_you' || v === 'THANK_YOU') return 'THANK_YOU';
  if (v === 'section18a_certificate' || v === 'SECTION_18A') return 'SECTION_18A';
  return v;
};

const resendDonationEmail = async (emailLogId, userId) => {
  const log = await donationModel.getEmailLogById(emailLogId);
  if (!log) fail(404, 'Email log not found.');

  const donation = await donationModel.getDonationById(log.donation_id);
  if (!donation) fail(404, 'Donation not found.');

  const emailType = normaliseEmailType(log.email_type);

  if (emailType === 'THANK_YOU') {
    const sent = await sendThankYouEmail(donation, userId);
    return { ...log, ...(sent || {}), emailType };
  }
  if (emailType === 'SECTION_18A') {
    const sent = await sendSection18ACertificateEmail(donation, userId);
    return { ...log, ...(sent || {}), emailType };
  }

  fail(400, `Cannot resend email of unsupported type "${log.email_type}".`);
};

// ── Section 18A Certificate Settings ─────────────────────────
// Single-row settings table (id = 1). getSettings returns the current
// configuration; updateSettings validates and persists changes.
const getSection18ASettings = async () => {
  const section18ASettings = await donationModel.getSection18ASettings();
  if (!section18ASettings) {
    fail(404, 'Section 18A settings have not been initialized.');
  }
  return section18ASettings;
};

const updateSection18ASettings = async (payload) => {
  // Validate email format if provided
  if (payload.contactEmail && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(payload.contactEmail)) {
    fail(400, 'Invalid contact email format.');
  }

  const updatedSettings = await donationModel.updateSection18ASettings({
    organisationName: payload.organisationName,
    organisationAddress: payload.organisationAddress,
    contactName: payload.contactName,
    contactEmail: payload.contactEmail,
    contactPhone: payload.contactPhone,
    pbaDeclaration: payload.pbaDeclaration,
    certificatePrefix: payload.certificatePrefix,
  });

  return updatedSettings;
};

